from datetime import date, datetime
from decimal import Decimal
from typing import Protocol

from fleet.models import (DeletedRecord, Driver, ExpiringDocument, FuelRecord, HistoryEntry, MaintenanceRecord,
                          NewDriver, NewVehicle, Trip, Vehicle, VehicleCosts, VehicleStats)

# repository contracts, the implementations are in the neighbouring modules


class IVehicleRepository(Protocol):
    def get_all(self) -> list[Vehicle]: ...
    def get_by_id(self, vehicle_id: int) -> Vehicle | None: ...
    def get_deleted(self) -> list[DeletedRecord]: ...
    def get_available_for_driver(self, driver_id: int) -> list[Vehicle]: ...
    def add(self, vehicle: NewVehicle) -> int: ...
    def update(self, vehicle_id: int, *, department_id: int | None = None, plate_number: str | None = None,
               color: str | None = None, odometer_km: int | None = None) -> None: ...
    def assign_driver(self, vehicle_id: int, driver_id: int, date_from: date) -> None: ...
    def delete(self, vehicle_id: int) -> None: ...
    def restore(self, vehicle_id: int) -> None: ...


class IDriverRepository(Protocol):
    def get_all(self) -> list[Driver]: ...
    def get_by_id(self, driver_id: int) -> Driver | None: ...
    def get_by_license(self, license_number: str) -> Driver | None: ...
    def search_by_last_name(self, last_name: str) -> list[Driver]: ...
    def get_deleted(self) -> list[DeletedRecord]: ...
    def add(self, driver: NewDriver) -> int: ...
    def update(self, driver_id: int, *, department_id: int | None = None, phone: str | None = None,
               email: str | None = None, license_number: str | None = None,
               license_expiry: date | None = None) -> None: ...
    def add_license_category(self, driver_id: int, category_code: str, obtained: date) -> None: ...
    def delete(self, driver_id: int) -> None: ...
    def restore(self, driver_id: int) -> None: ...


class ITripRepository(Protocol):
    def get_by_id(self, trip_id: int) -> Trip | None: ...
    def get_active(self) -> list[Trip]: ...
    def get_by_driver(self, driver_id: int, date_from: date, date_to: date) -> list[Trip]: ...
    def plan(self, vehicle_id: int, driver_id: int, route_id: int | None, purpose: str,
             planned_start: datetime) -> int: ...
    def start(self, trip_id: int) -> None: ...
    def complete(self, trip_id: int, end_odometer: int, notes: str | None = None) -> None: ...
    def cancel(self, trip_id: int, reason: str) -> None: ...


class IFuelRecordRepository(Protocol):
    def get_by_vehicle(self, vehicle_id: int, limit: int = 10) -> list[FuelRecord]: ...
    def add(self, vehicle_id: int, driver_id: int | None, liters: Decimal, price_per_liter: Decimal,
            station: str | None, refuel_date: datetime | None = None) -> int: ...


class IMaintenanceRepository(Protocol):
    def get_by_id(self, record_id: int) -> MaintenanceRecord | None: ...
    def get_by_vehicle(self, vehicle_id: int) -> list[MaintenanceRecord]: ...
    def schedule(self, vehicle_id: int, service_center_id: int, maintenance_type_id: int, scheduled: date,
                 description: str | None) -> int: ...
    def start(self, record_id: int) -> None: ...
    def complete(self, record_id: int, cost: Decimal, description: str | None = None) -> None: ...
    def delete(self, record_id: int) -> None: ...


class IReportRepository(Protocol):
    def get_expiring_documents(self) -> list[ExpiringDocument]: ...
    def get_vehicle_stats(self) -> list[VehicleStats]: ...
    def get_vehicle_costs(self, vehicle_id: int, date_from: date, date_to: date) -> VehicleCosts: ...
    def get_fuel_consumption(self, vehicle_id: int, date_from: date, date_to: date) -> Decimal | None: ...
    def get_history(self, table: str, record_id: int) -> list[HistoryEntry]: ...
    def refresh_statistics(self) -> None: ...
